vi.mock('@/lib/runtime-auth-config', () => ({ readRuntimeAuthConfig: vi.fn(() => ({ authToken: 'owner-token', webPassword: 'owner-password', webSessionSecret: 'session-secret' })) }));
vi.mock('@/lib/study-coaching-executor', () => ({ executeStudyCoaching: vi.fn() }));
