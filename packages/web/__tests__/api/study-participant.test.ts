let home: string;
beforeEach(() => { home = fs.mkdtempSync(path.join(os.tmpdir(), 'participant-api-')); vi.spyOn(os, 'homedir').mockReturnValue(home); vi.mocked(readRuntimeAuthConfig).mockReturnValue({ authToken: 'owner-token', webPassword: 'owner-password', webSessionSecret: 'session-secret' }); });
afterEach(() => { vi.restoreAllMocks(); fs.rmSync(home, { recursive: true, force: true }); });
function prepared() { let protocol = blankStudyProtocol('en'); for (const field of studyFields(protocol, 'en'))
    protocol = changeDraft(protocol, field.path, 'PRIVATE ' + field.path); protocol.title = 'Synthetic study'; protocol.consent = 'Consent to synthetic QA'; protocol.withdrawal = 'Stop or erase'; const d = createStudy(testMindRoot, { requestId: 'participant-api', protocol }); const s = freezeStudy(testMindRoot, d.id, { version: d.version, confirmed: true, reviewedBy: 'owner', reviewNote: 'QA' }); const i = issueStudyInvitation(testMindRoot, s.id, { requestId: 'one-invite', protocolHash: s.protocolHash, expiresAt: new Date(Date.now() + 86400000).toISOString() }); return { s, i, ctx: { params: Promise.resolve({ id: s.id }) } }; }
const request = (id: string, method = 'GET', body?: unknown, cookie = '', extra: Record<string, string> = {}) => new NextRequest('http://localhost/api/study/participate/' + id, { method, headers: { Cookie: cookie, ...extra }, ...(body ? { body: JSON.stringify(body) } : {}) });
it('exchanges only a study invitation for a scoped HttpOnly session and exposes no future materials', async () => {
    const { s, i, ctx } = prepared();
    expect((await GET(request(s.id), ctx)).status).toBe(401);
    expect((await GET(request(s.id, 'GET', undefined, '', { Authorization: 'Bearer owner-token' }), ctx)).status).toBe(401);
    const session = await POST(request(s.id, 'POST', { token: i.token }), ctx);
    expect(session.status).toBe(200);
    const setCookie = session.headers.get('set-cookie')!;
    expect(setCookie).toContain('HttpOnly');
    expect(setCookie).toContain('SameSite=strict');
    expect(setCookie).toContain('Path=/api/study/participate/' + s.id);
    const cookie = setCookie.split(';')[0]!;
    const rejectedSwitch = await POST(request(s.id, 'POST', { token: 'x'.repeat(43) }, cookie), ctx);
    expect(rejectedSwitch.status).toBe(401);
    expect(rejectedSwitch.headers.get('set-cookie')).toContain('Max-Age=0');
    const consent = await GET(request(s.id, 'GET', undefined, cookie), ctx);
    expect(consent.headers.get('cache-control')).toContain('no-store');
    expect(consent.headers.get('access-control-allow-origin')).toBeNull();
    expect(JSON.stringify(await consent.json())).not.toContain('PRIVATE');
    const joined = await PATCH(request(s.id, 'PATCH', { action: 'join', protocolHash: s.protocolHash, consentAccepted: true }, cookie), ctx);
    expect(joined.status).toBe(200);
    const result = await joined.json();
    expect(result.view.kind).toBe('participant');
    expect((await PATCH(request(s.id, 'PATCH', { action: 'open', version: result.view.participant.version, participantId: 'injected' }, cookie), ctx)).status).toBe(400);
    const opened = await PATCH(request(s.id, 'PATCH', { action: 'open', version: result.view.participant.version }, cookie), ctx);
    const value = JSON.stringify(await opened.json());
    expect(value).toContain('PRIVATE tasks.0.prompt');
    expect(value).not.toMatch(/tasks.1|reference|expectedRuntime|rubric/);
    const state = await GET(request(s.id, 'GET', undefined, cookie), ctx);
    const stateView = (await state.json()).view;
    const saved = await PATCH(request(s.id, 'PATCH', { action: 'answer', version: stateView.participant.version, answer: 'QA', confidence: null, assistance: 'none', familiar: false }, cookie), ctx);
    const savedView = (await saved.json()).view;
    expect((await PATCH(request(s.id, 'PATCH', { action: 'answer', version: stateView.participant.version, answer: 'Retry after a lost response', confidence: null, assistance: 'none', familiar: false }, cookie), ctx)).status).toBe(409);
    expect((await PATCH(request(s.id, 'PATCH', { action: 'open', version: savedView.participant.version }, cookie), ctx)).status).toBe(503);
});
