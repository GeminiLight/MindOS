#!/usr/bin/env node
/**
 * Bundle the agent-config adapter layer into a self-contained ESM file the
 * product CLI can import.
 *
 * The CLI (`packages/mindos/bin/lib`) used to hand-copy the MCP agent registry
 * and the JSONC / TOML / YAML parsers so it could stay on node builtins only
 * (the Bun single-binary build cannot resolve bare npm specifiers). That copy
 * drifted from `src/` repeatedly. Instead we generate ONE bundle from
 * `src/agent/config/index.ts` — the same source the product server and the Web
 * host import — with `jsonc-parser` inlined and only `node:*` left external.
 *
 * Output: `packages/mindos/bin/lib/generated/agent-config.mjs` (a build
 * artifact; gitignored, regenerated by `pnpm build` / `prepack` and on demand
 * by `bin/lib/agent-config.js` in a monorepo checkout).
 *
 * Keep in sync with: packages/mindos/bin/lib/agent-config.js (the loader),
 * tests/bun-single-binary-contract.test.ts (no bare imports in the bundle),
 * wiki/specs/spec-agent-config-adapter.md.
 */
import { existsSync, mkdirSync, renameSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const productRoot = resolve(root, 'packages', 'mindos');
const requireFromProduct = createRequire(resolve(productRoot, 'package.json'));

const entryPoint = resolve(productRoot, 'src', 'agent', 'config', 'index.ts');
const outfile = resolve(productRoot, 'bin', 'lib', 'generated', 'agent-config.mjs');

if (!existsSync(entryPoint)) {
  throw new Error(`[build-cli-bundles] Missing agent-config entrypoint: ${entryPoint}`);
}

const { build } = requireFromProduct('esbuild');

mkdirSync(dirname(outfile), { recursive: true });

// Write to a temp file then rename so concurrent vitest workers (or a CLI
// invocation racing a build) never import a half-written bundle.
const tmpfile = `${outfile}.tmp-${process.pid}.${Date.now().toString(36)}`;
try {
  await build({
    entryPoints: [entryPoint],
    outfile: tmpfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node18',
    // Prefer the ESM `module` build of dependencies (jsonc-parser ships a UMD
    // `main` whose dynamic `require('./impl/*')` cannot run in an ESM bundle).
    mainFields: ['module', 'main'],
    // Inline jsonc-parser; leave node builtins external (platform: 'node' does
    // this) so the Bun single binary can still resolve them.
    external: ['node:*'],
    minify: true,
    sourcemap: false,
    logLevel: 'warning',
    banner: {
      js: '// Generated by scripts/build-cli-bundles.mjs from src/agent/config — DO NOT EDIT.',
    },
  });
  renameSync(tmpfile, outfile);
} catch (error) {
  rmSync(tmpfile, { force: true });
  throw error;
}

console.error(`[build-cli-bundles] OK - bundled agent-config → bin/lib/generated/agent-config.mjs`);
